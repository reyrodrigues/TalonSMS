import { getJson, postJson } from './http'

/**
 * Talks to the Breeze endpoints without the Breeze client.
 *
 * Only two pieces of that library's behaviour are actually needed, and both are small:
 *  - queries go on the query string as Breeze's own JSON ({ where, orderBy, skip, take, expand,
 *    inlineCount }). The OData-style $top/$orderby parameters the old client emitted are ignored
 *    by this server.
 *  - saves post a bundle of entities, each tagged with an `entityAspect` describing its type and
 *    state. New rows use negative ids and the response maps them to the real keys.
 *
 * Everything else Breeze offered — an identity map, change tracking, metadata-driven validation —
 * is replaced here by ordinary typed objects and explicit saves.
 */

export type EntityState = 'Added' | 'Modified' | 'Deleted'

export interface BreezeQuery {
  where?: Record<string, unknown>
  orderBy?: string[]
  skip?: number
  take?: number
  expand?: string[]
  inlineCount?: boolean
  select?: string[]
  /**
   * Arguments for a Breeze endpoint that takes them, e.g. `DistributionBeneficiaries(int id)`.
   * They ride after the JSON blob as ordinary query-string pairs, which is where model binding
   * looks for them — the same placement `withParameters` used.
   */
  parameters?: Record<string, string | number>
}

export interface PagedResult<T> {
  rows: T[]
  total: number
}

interface QueryEnvelope<T> {
  Results: T[]
  InlineCount: number | null
}

export type BreezeContext = 'EVM' | 'Admin'

const NAMESPACE: Record<BreezeContext, string> = {
  EVM: 'TalonAdmin.Models.Vouchers',
  Admin: 'TalonAdmin.Models.Admin'
}

function queryUrl(context: BreezeContext, resource: string, query?: BreezeQuery): string {
  const url = `/breeze/${context}/${resource}`
  if (!query) return url

  const { parameters, ...rest } = query
  const parts: string[] = []

  if (Object.keys(rest).length > 0) parts.push(encodeURIComponent(JSON.stringify(rest)))
  if (parameters) parts.push(new URLSearchParams(asStrings(parameters)).toString())

  return parts.length === 0 ? url : `${url}?${parts.join('&')}`
}

const asStrings = (values: Record<string, string | number>) =>
  Object.fromEntries(Object.entries(values).map(([key, value]) => [key, String(value)]))

/** Runs a query that does not ask for a count; the server answers with a bare array. */
export async function query<T>(
  context: BreezeContext,
  resource: string,
  q?: BreezeQuery
): Promise<T[]> {
  const result = await getJson<T[] | QueryEnvelope<T>>(queryUrl(context, resource, q))

  return Array.isArray(result) ? result : result.Results
}

/** Runs a paged query. `inlineCount` is forced on so the grid can show a total. */
export async function queryPage<T>(
  context: BreezeContext,
  resource: string,
  q: BreezeQuery
): Promise<PagedResult<T>> {
  const result = await getJson<QueryEnvelope<T>>(
    queryUrl(context, resource, { ...q, inlineCount: true })
  )

  return { rows: result.Results ?? [], total: result.InlineCount ?? 0 }
}

export async function first<T>(
  context: BreezeContext,
  resource: string,
  q: BreezeQuery
): Promise<T | null> {
  const rows = await query<T>(context, resource, { ...q, take: 1 })
  return rows[0] ?? null
}

interface EntityAspect {
  entityTypeName: string
  defaultResourceName: string
  entityState: EntityState
  originalValuesMap: Record<string, unknown>
  autoGeneratedKey: { propertyName: string; autoGeneratedKeyType: string }
}

export interface SaveEntity {
  entityAspect: EntityAspect
  [key: string]: unknown
}

export interface KeyMapping {
  EntityTypeName: string
  TempValue: number
  RealValue: number
}

export interface SaveResult<T = unknown> {
  Entities: T[]
  KeyMappings: KeyMapping[]
  /** Resolves the real key assigned to a row that was saved with a temporary negative id. */
  realId(tempId: number): number
}

let nextTempId = -1

/** Temporary key for a new row. Breeze expects these to be negative and unique per bundle. */
export function tempId(): number {
  return nextTempId--
}

export function added(
  context: BreezeContext,
  typeName: string,
  resourceName: string,
  values: Record<string, unknown>,
  id: number = tempId()
): SaveEntity {
  return withAspect(context, typeName, resourceName, 'Added', { ...values, Id: id }, {})
}

/**
 * An Added row whose key the client already knows — a composite key, or one the server does not
 * generate. No temporary id is assigned and the server is told not to map one back.
 *
 * `keyProperty` must name a real property: the server passes it straight to EF, which rejects an
 * empty string. For a composite key, naming either part is enough.
 */
export function addedWithKey(
  context: BreezeContext,
  typeName: string,
  resourceName: string,
  values: Record<string, unknown>,
  keyProperty: string
): SaveEntity {
  return withAspect(context, typeName, resourceName, 'Added', values, {}, clientKey(keyProperty))
}

/** Key descriptor for a row the client keys itself rather than letting the database assign one. */
export const clientKey = (propertyName: string): GeneratedKey => ({
  propertyName,
  autoGeneratedKeyType: 'None'
})

export function modified(
  context: BreezeContext,
  typeName: string,
  resourceName: string,
  values: Record<string, unknown>,
  originalValues: Record<string, unknown>,
  key: GeneratedKey = IDENTITY_KEY
): SaveEntity {
  return withAspect(context, typeName, resourceName, 'Modified', values, originalValues, key)
}

export function deleted(
  context: BreezeContext,
  typeName: string,
  resourceName: string,
  values: Record<string, unknown>,
  key: GeneratedKey = IDENTITY_KEY
): SaveEntity {
  return withAspect(context, typeName, resourceName, 'Deleted', values, {}, key)
}

type GeneratedKey = EntityAspect['autoGeneratedKey']

const IDENTITY_KEY: GeneratedKey = { propertyName: 'Id', autoGeneratedKeyType: 'Identity' }

function withAspect(
  context: BreezeContext,
  typeName: string,
  resourceName: string,
  entityState: EntityState,
  values: Record<string, unknown>,
  originalValuesMap: Record<string, unknown>,
  autoGeneratedKey: GeneratedKey = IDENTITY_KEY
): SaveEntity {
  // Navigation properties come back from queries populated; sending them back confuses the
  // server's graph handling, so only scalars are round-tripped.
  const scalars: Record<string, unknown> = {}
  for (const [key, value] of Object.entries(values)) {
    if (key === 'entityAspect' || key === '$type') continue
    if (value !== null && typeof value === 'object') continue
    scalars[key] = value
  }

  return {
    ...scalars,
    entityAspect: {
      entityTypeName: `${typeName}:#${NAMESPACE[context]}`,
      defaultResourceName: resourceName,
      entityState,
      originalValuesMap,
      autoGeneratedKey
    }
  }
}

export async function saveChanges<T = unknown>(
  context: BreezeContext,
  entities: SaveEntity[]
): Promise<SaveResult<T>> {
  const payload = await postJson<{ Entities: T[]; KeyMappings: KeyMapping[] }>(
    `/breeze/${context}/SaveChanges`,
    { entities, saveOptions: {} }
  )

  const mappings = new Map<number, number>()
  for (const mapping of payload.KeyMappings ?? []) {
    mappings.set(mapping.TempValue, mapping.RealValue)
  }

  return {
    Entities: payload.Entities ?? [],
    KeyMappings: payload.KeyMappings ?? [],
    realId(temp: number) {
      const real = mappings.get(temp)
      if (real === undefined) {
        throw new Error(`No key mapping was returned for temporary id ${temp}.`)
      }
      return real
    }
  }
}

/**
 * Turns a free-text search box into a Breeze `where` clause across several columns.
 * Mirrors the filterFunction each AngularJS screen used to declare.
 */
export function containsAny(term: string, fields: string[]): Record<string, unknown> | undefined {
  const value = term.trim()
  if (!value) return undefined

  return { or: fields.map(field => ({ [field]: { contains: value } })) }
}
