import { describe, expect, it } from 'vitest'
import { added, containsAny, deleted, modified } from './breeze'

/**
 * The wire format is the part of this client that has to agree exactly with the server. It is
 * pure logic, so it is worth pinning down here rather than only through the browser.
 */

describe('save bundles', () => {
  it('tags a new row with its type, resource and a negative id', () => {
    const entity = added('EVM', 'Beneficiary', 'Beneficiaries', { FirstName: 'Amal' }, -1)

    expect(entity.Id).toBe(-1)
    expect(entity.FirstName).toBe('Amal')
    expect(entity.entityAspect).toEqual({
      entityTypeName: 'Beneficiary:#TalonAdmin.Models.Vouchers',
      defaultResourceName: 'Beneficiaries',
      entityState: 'Added',
      originalValuesMap: {},
      autoGeneratedKey: { propertyName: 'Id', autoGeneratedKeyType: 'Identity' }
    })
  })

  it('uses the admin namespace for admin entities', () => {
    const entity = added('Admin', 'Country', 'Countries', { Name: 'Jordan' })

    expect(entity.entityAspect.entityTypeName).toBe('Country:#TalonAdmin.Models.Admin')
  })

  it('carries the original values on a modified row', () => {
    const entity = modified(
      'EVM',
      'Beneficiary',
      'Beneficiaries',
      { Id: 3, LastName: 'Renamed' },
      { LastName: 'Original' }
    )

    expect(entity.entityAspect.entityState).toBe('Modified')
    expect(entity.entityAspect.originalValuesMap).toEqual({ LastName: 'Original' })
  })

  it('marks a deleted row without inventing original values', () => {
    const entity = deleted('EVM', 'Vendor', 'Vendors', { Id: 7, Name: 'Al Salam' })

    expect(entity.entityAspect.entityState).toBe('Deleted')
    expect(entity.Id).toBe(7)
  })

  it('strips expanded navigations and the type discriminator', () => {
    // A row read back from a query arrives with $type and its expanded navigations attached.
    // Posting those back confuses the server's graph handling.
    const entity = modified(
      'EVM',
      'Beneficiary',
      'Beneficiaries',
      {
        $type: 'TalonAdmin.Models.Vouchers.Beneficiary, TalonAdmin',
        Id: 3,
        FirstName: 'Amal',
        Group: { Id: 1, Name: 'Cohort A' },
        Location: null
      },
      {}
    )

    expect(entity).not.toHaveProperty('$type')
    expect(entity).not.toHaveProperty('Group')
    expect(entity.FirstName).toBe('Amal')
    // an explicit null is a real value, not a navigation to drop
    expect(entity.Location).toBeNull()
  })

  it('allocates a distinct temporary id per new row', () => {
    const first = added('EVM', 'Location', 'Locations', { Name: 'Amman' })
    const second = added('EVM', 'Location', 'Locations', { Name: 'Irbid' })

    expect(first.Id).not.toBe(second.Id)
    expect(first.Id as number).toBeLessThan(0)
  })
})

describe('search clauses', () => {
  it('builds an or-of-contains across the searched fields', () => {
    expect(containsAny('amal', ['FirstName', 'LastName'])).toEqual({
      or: [{ FirstName: { contains: 'amal' } }, { LastName: { contains: 'amal' } }]
    })
  })

  it('produces no clause for an empty search so the query is unfiltered', () => {
    expect(containsAny('   ', ['FirstName'])).toBeUndefined()
    expect(containsAny('', ['FirstName'])).toBeUndefined()
  })
})
